"use client";

import { useEffect, useState } from "react";

interface InstallPromptEvent extends Event {
  prompt(): Promise<void>;
  userChoice: Promise<{ outcome: "accepted" | "dismissed" }>;
}

export function usePwa() {
  const [prompt, setPrompt] = useState<InstallPromptEvent | null>(null);
  const [installed, setInstalled] = useState(false);
  const [online, setOnline] = useState(true);

  useEffect(() => {
    const display = window.matchMedia("(display-mode: standalone)");
    const updateDisplay = () => {
      const iosNavigator = navigator as Navigator & { standalone?: boolean };
      setInstalled(display.matches || iosNavigator.standalone === true);
    };
    const updateConnection = () => setOnline(navigator.onLine);
    const savePrompt = (event: Event) => {
      event.preventDefault();
      setPrompt(event as InstallPromptEvent);
    };
    const markInstalled = () => {
      setInstalled(true);
      setPrompt(null);
    };

    updateDisplay();
    updateConnection();
    display.addEventListener("change", updateDisplay);
    window.addEventListener("online", updateConnection);
    window.addEventListener("offline", updateConnection);
    window.addEventListener("beforeinstallprompt", savePrompt);
    window.addEventListener("appinstalled", markInstalled);

    // The worker is generated by the production build.
    if (process.env.NODE_ENV === "production" && "serviceWorker" in navigator) {
      void navigator.serviceWorker.register("/sw.js", { updateViaCache: "none" }).catch((error) => {
        console.warn("Sceneform could not register its service worker.", error);
      });
    }

    return () => {
      display.removeEventListener("change", updateDisplay);
      window.removeEventListener("online", updateConnection);
      window.removeEventListener("offline", updateConnection);
      window.removeEventListener("beforeinstallprompt", savePrompt);
      window.removeEventListener("appinstalled", markInstalled);
    };
  }, []);

  async function requestInstall() {
    if (!prompt) return false;

    setPrompt(null);
    try {
      await prompt.prompt();
      const choice = await prompt.userChoice;
      if (choice.outcome === "accepted") setInstalled(true);
      return true;
    } catch {
      return false;
    }
  }

  return { installed, online, requestInstall };
}
